function readStoredLanguage() {
  try {
    const value = localStorage.getItem(STORAGE_KEY);
    return SUPPORTED.includes(value) ? value : "English";
  } catch {
    return "English";
  }
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(readStoredLanguage);

  const setLanguage = (nextLanguage) => {
    const next = SUPPORTED.includes(nextLanguage) ? nextLanguage : "English";
    setLanguageState(next);
    try {
      localStorage.setItem(STORAGE_KEY, next);
      window.dispatchEvent(new CustomEvent("cyberrakshak:language-changed", { detail: next }));
    } catch {
      // Ignore storage restrictions.
    }
  };

  const value = useMemo(() => ({
    language,
    setLanguage,
    languages: SUPPORTED,
    t: (key) => translations[language]?.[key] ?? translations.English[key] ?? key,
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
